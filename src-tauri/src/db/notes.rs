//! Meeting notes storage.

use rusqlite::{OptionalExtension, params};

use super::{Db, DbError};
use crate::notes::{ActionItem, Notes};

#[derive(Debug, serde::Serialize)]
#[serde(rename_all = "camelCase")]
pub struct StoredNotes {
    pub notes: Notes,
    pub provider: Option<String>,
    pub model: Option<String>,
    pub generated_at: Option<String>,
    pub edited: bool,
}

#[derive(Debug, serde::Serialize)]
#[serde(rename_all = "camelCase")]
pub struct DayActionItem {
    pub meeting_id: i64,
    pub meeting_title: Option<String>,
    pub index: usize,
    pub item: ActionItem,
}

type NotesRow = (
    Option<String>,
    Option<String>,
    Option<String>,
    Option<String>,
    Option<String>,
    Option<String>,
    bool,
);

impl Db {
    pub fn get_notes(&self, meeting_id: i64) -> Result<Option<StoredNotes>, DbError> {
        let row: Option<NotesRow> = self
            .lock()?
            .query_row(
                "SELECT summary, decisions_json, action_items_json, provider, model, generated_at, edited
                 FROM meeting_notes WHERE meeting_id = ?1",
                params![meeting_id],
                |r| Ok((r.get(0)?, r.get(1)?, r.get(2)?, r.get(3)?, r.get(4)?, r.get(5)?, r.get(6)?)),
            )
            .optional()?;
        let Some((summary, decisions, items, provider, model, generated_at, edited)) = row else {
            return Ok(None);
        };
        Ok(Some(StoredNotes {
            notes: Notes {
                summary: summary.unwrap_or_default(),
                decisions: decisions
                    .map(|d| serde_json::from_str(&d))
                    .transpose()?
                    .unwrap_or_default(),
                action_items: items
                    .map(|d| serde_json::from_str(&d))
                    .transpose()?
                    .unwrap_or_default(),
            },
            provider,
            model,
            generated_at,
            edited,
        }))
    }

    pub fn save_notes(
        &self,
        meeting_id: i64,
        notes: &Notes,
        source: Option<(&str, &str, &str)>,
    ) -> Result<(), DbError> {
        let decisions = serde_json::to_string(&notes.decisions)?;
        let items = serde_json::to_string(&notes.action_items)?;
        let conn = self.lock()?;
        match source {
            // Generated by a model: replace everything.
            Some((provider, model, at)) => conn.execute(
                "INSERT INTO meeting_notes (meeting_id, summary, decisions_json, action_items_json, provider, model, generated_at, edited)
                 VALUES (?1, ?2, ?3, ?4, ?5, ?6, ?7, 0)
                 ON CONFLICT(meeting_id) DO UPDATE SET summary = excluded.summary,
                   decisions_json = excluded.decisions_json, action_items_json = excluded.action_items_json,
                   provider = excluded.provider, model = excluded.model, generated_at = excluded.generated_at, edited = 0",
                params![meeting_id, notes.summary, decisions, items, provider, model, at],
            )?,
            // Edited by the user: keep where it came from.
            None => conn.execute(
                "INSERT INTO meeting_notes (meeting_id, summary, decisions_json, action_items_json, edited)
                 VALUES (?1, ?2, ?3, ?4, 1)
                 ON CONFLICT(meeting_id) DO UPDATE SET summary = excluded.summary,
                   decisions_json = excluded.decisions_json, action_items_json = excluded.action_items_json, edited = 1",
                params![meeting_id, notes.summary, decisions, items],
            )?,
        };
        Ok(())
    }

    /// Action items from meetings that started in [from, to).
    pub fn action_items_between(
        &self,
        from: &str,
        to: &str,
    ) -> Result<Vec<DayActionItem>, DbError> {
        let conn = self.lock()?;
        let rows: Vec<(i64, Option<String>, Option<String>)> = conn
            .prepare(
                "SELECT m.id, m.title, n.action_items_json FROM meetings m
                 JOIN meeting_notes n ON n.meeting_id = m.id
                 WHERE m.started_at >= ?1 AND m.started_at < ?2 ORDER BY m.started_at",
            )?
            .query_map(params![from, to], |r| Ok((r.get(0)?, r.get(1)?, r.get(2)?)))?
            .collect::<Result<_, _>>()?;
        let mut out = Vec::new();
        for (meeting_id, meeting_title, json) in rows {
            let items: Vec<ActionItem> = json
                .map(|j| serde_json::from_str(&j))
                .transpose()?
                .unwrap_or_default();
            for (index, item) in items.into_iter().enumerate() {
                out.push(DayActionItem {
                    meeting_id,
                    meeting_title: meeting_title.clone(),
                    index,
                    item,
                });
            }
        }
        Ok(out)
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn notes_round_trip_and_day_items() {
        let db = Db::open_in_memory().unwrap();
        let id = db.create_meeting("2026-11-27T10:00:00Z", "a").unwrap();
        assert!(db.get_notes(id).unwrap().is_none());
        let notes = Notes {
            summary: "- x".into(),
            decisions: vec!["d".into()],
            action_items: vec![ActionItem {
                text: "t".into(),
                owner: Some("You".into()),
                due: None,
                done: false,
            }],
        };
        db.save_notes(id, &notes, Some(("ollama", "llama3.2", "now")))
            .unwrap();
        let s = db.get_notes(id).unwrap().unwrap();
        assert_eq!(s.notes, notes);
        assert!(!s.edited);
        let mut edited = notes.clone();
        edited.action_items[0].done = true;
        db.save_notes(id, &edited, None).unwrap();
        let s = db.get_notes(id).unwrap().unwrap();
        assert!(s.edited);
        assert_eq!(s.provider.as_deref(), Some("ollama"));
        let items = db
            .action_items_between("2026-11-27T00:00:00Z", "2026-11-28T00:00:00Z")
            .unwrap();
        assert_eq!(items.len(), 1);
        assert!(items[0].item.done);
    }
}
